/** 根据ID获取技能 */
export function getSkillById(id: string): Skill | undefined {
  return skills.find(s => s.id === id)
}

/** 获取指定道修方向的初始技能 */
export function getInitialSkill(cultivationType: string): Skill {
  switch (cultivationType) {
    case 'sword': return skills.find(s => s.id === 'sword_basic')!
    case 'spirit': return skills.find(s => s.id === 'spirit_basic')!
    case 'demon': return skills.find(s => s.id === 'demon_basic')!
    default: return skills.find(s => s.id === 'general_attack')!
  }
}
